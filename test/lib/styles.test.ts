import { describe, expect, test } from 'vitest';

import { expectLineCount, expectScssExports, getCssVars, getSelectors, scss } from '../shared';

describe('styles namespace', () => {
	test('check exports', () => {
		expectScssExports('styles', {
			functions: [],
			mixins: 'base code del em figure heading hr link ol p pre quote strong table ul'.split(
				' ',
			),
			variables: [],
		});
	});

	test('output base styles', () => {
		const { css, error } = scss`
			@include styles.base();
		`;

		// Check output
		expect(error).toBeUndefined();
		expectLineCount(css, 30);

		// Variables are correct
		const variables = getCssVars(css);
		expect(variables).toStrictEqual([
			'--rmd-base-font: ui-monospace, monospace',
			'--rmd-code-font: inherit',
			'--rmd-line-height: 1.5',
			'--rmd-ul-indent: 3ch',
			'--rmd-ol-indent: 3ch',
			'--rmd-hn-prefix: "#"',
			'--rmd-h1-line: "========================================"',
			'--rmd-h2-line: "----------------------------------------"',
			'--rmd-ul-dash: "-"',
			'--rmd-ul-star: "*"',
			'--rmd-ul-plus: "+"',
			'--rmd-ol-mark: "."',
			'--rmd-pre-ticks: "```"',
			'--rmd-pre-tilde: "~~~"',
			'--rmd-pre-tilde-line: "~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~"',
			'--rmd-quote-mark: ">\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a>\\a"',
			'--rmd-quote-rtl: "<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a<\\a"',
			'--rmd-hr-stars: "* * * *"',
			'--rmd-hr-dashes: "-------"',
			'--rmd-table-vline: "|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a|\\a"',
			'--rmd-table-hline: "----------------------------------------"',
		]);

		// Check selectors
		const selectors = getSelectors(css);
		expect(selectors).toStrictEqual([
			// Base selector is duplicated because it's generated by two separate
			// mixin calls, and we don't run postcss to merge them when using the
			// Sass library only.
			'.remarkdown',
			'.remarkdown',
			'.remarkdown :is(pre, code, kbd, samp)',
		]);
	});

	test('can output any style even if base is not called', () => {
		const { css, error } = scss`
			@include styles.hr();
		`;
		expect(error).toBeUndefined();
		expectLineCount(css, 25);

		// CSS variables are used, but not defined
		expect(css).not.toMatch('--rmd-hr-dashes:');
		expect(css).not.toMatch('--rmd-hr-stars:');
		expect(css).toMatch('var(--rmd-hr-dashes)');
		expect(css).toMatch('var(--rmd-hr-stars)');
	});

	test('can output the same style many times', () => {
		const { css, error, logs } = scss`
			@each $n in (1 2 3) {
				@include styles.em();
				@include styles.strong();
			}
		`;
		expect(error).toBeUndefined();
		expectLineCount(css, 90);

		// Check selectors
		const selectors = getSelectors(css);
		expect(selectors.length).toBe(18);

		const uniqueSelectors = [...new Set(selectors)];
		expect(uniqueSelectors).toStrictEqual([
			'.remarkdown em',
			'.remarkdown em::before, .remarkdown em::after',
			'.remarkdown.em-underscore em::before, .remarkdown.em-underscore em::after',
			'.remarkdown strong',
			'.remarkdown strong::before, .remarkdown strong::after',
			'.remarkdown.strong-underscore strong::before, .remarkdown.strong-underscore strong::after',
		]);
	});
});
